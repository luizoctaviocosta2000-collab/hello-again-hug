import { describe, expect, test } from "bun:test";
import { isOwnedPhotoPath, isOwnedPhotoRow } from "../supabase/functions/_shared/property-photo-ownership";

const userA = "11111111-1111-4111-8111-111111111111";
const userB = "22222222-2222-4222-8222-222222222222";
const propertyA = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
const propertyB = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";
const filename = "dddddddd-dddd-4ddd-8ddd-dddddddddddd.jpg";
const valid = `${userA}/${propertyA}/${filename}`;

describe("public property share: privileged photo URL authorization", () => {
  test("accepts the path generated by the actual property photo uploader", () => {
    expect(isOwnedPhotoPath(valid, userA, propertyA)).toBe(true);
    expect(isOwnedPhotoPath(valid.replace(".jpg", ".webp"), userA, propertyA)).toBe(true);
  });

  test("rejects another user's photo, even if metadata points to the shared property", () => {
    expect(isOwnedPhotoPath(`${userB}/${propertyA}/${filename}`, userA, propertyA)).toBe(false);
  });

  test("rejects another property belonging to the same user", () => {
    expect(isOwnedPhotoPath(`${userA}/${propertyB}/${filename}`, userA, propertyA)).toBe(false);
  });

  test("rejects nested paths, missing filenames and path traversal", () => {
    const paths = [
      `${userA}/${propertyA}/`,
      `${userA}/${propertyA}/../${filename}`,
      `${userA}/${propertyA}/./${filename}`,
      `${userA}/${propertyA}/subdir/${filename}`,
      `${userA}/${propertyA}/../`,
      `${userA}/${propertyA}\\${filename}`,
    ];
    for (const path of paths) expect(isOwnedPhotoPath(path, userA, propertyA)).toBe(false);
  });

  test("rejects strange object keys and non-image extensions", () => {
    const paths = [
      `${userA}/${propertyA}/not-a-uuid.png`,
      `${userA}/${propertyA}/${filename}.html`,
      `${userA}/${propertyA}/%2e%2e%2f${filename}`,
      `${userA}/${propertyA}/${filename}?download=1`,
      `${userA}/${propertyA}/${filename}#x`,
    ];
    for (const path of paths) expect(isOwnedPhotoPath(path, userA, propertyA)).toBe(false);
  });

  test("rejects undefined, null, empty or malformed metadata", () => {
    expect(isOwnedPhotoPath(undefined, userA, propertyA)).toBe(false);
    expect(isOwnedPhotoPath(null, userA, propertyA)).toBe(false);
    expect(isOwnedPhotoPath("", userA, propertyA)).toBe(false);
    expect(isOwnedPhotoPath(valid, "", propertyA)).toBe(false);
  });

  test("requires metadata user_id, property_id and storage path to agree", () => {
    const good = { user_id: userA, property_id: propertyA, storage_path: valid };
    expect(isOwnedPhotoRow(good, userA, propertyA)).toBe(true);
    expect(isOwnedPhotoRow({ ...good, user_id: userB }, userA, propertyA)).toBe(false);
    expect(isOwnedPhotoRow({ ...good, property_id: propertyB }, userA, propertyA)).toBe(false);
    expect(isOwnedPhotoRow({ ...good, storage_path: `${userB}/${propertyA}/${filename}` }, userA, propertyA)).toBe(false);
  });
});
